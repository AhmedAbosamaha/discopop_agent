#!/usr/bin/env python3
"""T0.19 — packaging v8 (suite tsvc_c4) checked without a model, before a model reads it. Reads

  analysis/packages/                   the generator's validation log and every package file's digest, Mac and server
  preflight/t0_1_c4_sizes              the sizes
  preflight/t0_11_c4_a, _b, _c         DiscoPoP alone in three draws — which loops it parallelizes itself
  preflight/t0_14_c4_refs              the nine expert references through the harness
  checks/t0_13_c4_ceiling              the references of the loops under test with their directives removed
  checks/t0_19_s341_a, _b              s341 on v7's data against s341 on v8's, two draws
  analysis/gate_probe/                 the agent's own dependence stage on the plain right directive (no model)

    venv/bin/python evaluation/agent/results/T0_instruments/T0.19_packaging_v8/analysis/t019_readout.py
"""
import collections
import csv
import glob
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
G = HERE.parent
md = ["# T0.19 — packaging v8 (`tsvc_c4`) on the server, before a model reads it", "",
      "Generated by `analysis/t019_readout.py`. No model in anything here.", ""]

# (1) the packages
def digests(p):
    return {l.split()[1]: l.split()[0] for l in (HERE / "packages" / p).read_text().splitlines() if l.strip()}
mac, srv = digests("digests_mac.txt"), digests("digests_server.txt")
ok = lambda p: len(re.findall(r"  OK$", (HERE / "packages" / p).read_text(), re.M))
md += ["## 1. The packages", "",
       f"Validated by the generator: {ok('build_mac.log')} on the Mac, {ok('build_server.log')} on the server; none failed. "
       f"Files with a digest: {len(mac)} on the Mac, {len(srv)} on the server; with the same sha256 on both: "
       f"{sum(1 for k in mac if srv.get(k) == mac[k])}.", ""]

# (2) sizes
ch = json.loads(next(G.glob("preflight/t0_1_c4_sizes/chosen.json")).read_text())
ks = ch.get("kernels", ch)
md += ["## 2. Sizes", "", "| package | timing size | verification size | serial kernel time at the largest size measured |", "|---|---|---|---:|"]
for k in sorted(ks):
    v = ks[k]
    md.append(f"| `{k}` | {v['timing_size']} | {v['verification_size']} | {v['longest_measured']['kernel_s']:.2f} s ({v['longest_measured']['size']}) |")
md.append("")

# (3) classes
rows = collections.defaultdict(list)
for d in "abc":
    for f in sorted(glob.glob(str(G / f"preflight/t0_11_c4_{d}/benchmarks/tsvc_c4/*/*/*/rep1/trial.json"))):
        t = json.loads(Path(f).read_text())
        rows[t["benchmark"]].append((t["outcome"], t.get("baseline_pragmas"), t.get("pragmas_discopop"), t.get("gate_failures_phase_b") or {}))
md += ["## 3. DiscoPoP alone, three draws", "",
       "| package | outcome in the three draws | pragmas DiscoPoP offered | kept | refused by |", "|---|---|---|---|---|"]
for k in sorted(rows):
    r = rows[k]
    md.append(f"| `{k}` | {', '.join(x[0] for x in r)} | {', '.join(str(x[1]) for x in r)} | {', '.join(str(x[2]) for x in r)} | "
              + (", ".join(sorted({s for x in r for s in x[3]})) or "—") + " |")
md.append("")

# (4) references
md += ["## 4. The references through the harness", "",
       "| package | outcome | 6 threads | 12 threads | serial kernel | exact on the shipped input | largest relative difference on the perturbed input |",
       "|---|---|---:|---:|---:|---|---:|"]
for f in sorted(glob.glob(str(G / "preflight/t0_14_c4_refs/benchmarks/**/trial.json"), recursive=True)):
    t = json.loads(Path(f).read_text()); v = t["verify"]
    md.append(f"| `{t['benchmark']}` | {t['outcome']} | {v['par']['6']['kernel_speedup']:.2f}× | {v['par']['12']['kernel_speedup']:.2f}× | "
              f"{v['seq_kernel_median_s']:.2f} s ({v['verify_size']}) | {v['dump_exact']} | {v['dump_seeded_max_rel_err']:.1e} |")
md.append("")

# (5) ceiling
md += ["## 5. The references of the loops under test with their directives removed: does DiscoPoP write one?", "",
       "| package | result | directives in the reference | candidates DiscoPoP offered | applied |", "|---|---|---:|---:|---:|"]
for r in csv.DictReader(open(G / "checks/t0_13_c4_ceiling/ceiling.csv")):
    md.append(f"| `{r['loop']}` | {r['result']} | {r['expert_pragmas']} | {r['candidates']} | {r['applied']} |")
md.append("")

# (6) s341
md += ["## 6. `s341` on v7's data against v8's (DiscoPoP's view, two draws)", ""]
for d in "ab":
    t = (G / f"checks/t0_19_s341_{d}/screen.md").read_text().strip().splitlines()
    md += [f"Draw {d}:", ""] + t[:3] + [""]

# (7) the agent's dependence stage on the plain right directive
md += ["## 7. The agent's dependence stage on the plain right directive (profiles of draw a)", "", "```",
       (HERE / "gate_probe" / "gate_probe_server.txt").read_text().rstrip(), "```", ""]
(HERE / "t019_readout.md").write_text("\n".join(md) + "\n")
print("\n".join(md)[:6000])
