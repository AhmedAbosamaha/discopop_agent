#!/usr/bin/env python3
"""DiscoPoP B14 — what the fix changes on the programs the agent shipped, and that it changes nothing for DiscoPoP
alone on the 44 tsvc_c2 originals. Reads the two replays (`checks/b14_replay_before`, `checks/b14_replay_after`:
`tools/doall_replay.py`, the same archived programs on the profiler before and after the fix) and the class
draws (`t0_11_c2_a`-`c` before, `t0_11_c2_b14_a`-`b` after).

    venv/bin/python evaluation/agent/results/T0_instruments/B14_side_by_side_loops/analysis/b14_readout.py
"""
import collections
import glob
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[3] / "tools"))
sys.path.insert(0, str(HERE.parents[4] / "shared"))
import campaign  # noqa: E402

PARTS = [("e1_agent", "E1-v6 — the agent, its normal setup (`default_v4`)"),
         ("e2_evidence_1", "E2-v6 — evidence, one attempt"), ("e2_none_1", "E2-v6 — no evidence, one attempt"),
         ("e2_evidence_3", "E2-v6 — evidence, three attempts"), ("e2_none_3", "E2-v6 — no evidence, three attempts")]


def load(tag):
    out, digest = {}, set()
    for f in sorted(glob.glob(str(HERE.parent / "checks" / f"b14_replay_{tag}" / "*" / "results.jsonl"))):
        part = Path(f).parent.name
        digest.add(json.load(open(Path(f).parent / "manifest.json")).get("discopop_pass_sha256", "")[:12])
        for line in open(f):
            if line.strip():
                r = json.loads(line)
                r["part"] = part
                out[r["trial"]] = r
    return out, sorted(digest)


before, d_before = load("before")
after, d_after = load("after")
assert set(before) == set(after)
md = ["# DiscoPoP B14 — what the fix changes", "",
      f"Generated by `analysis/b14_readout.py`. Profiler build (first 12 digits of the pass's sha256): before "
      f"`{', '.join(d_before)}`, after `{', '.join(d_after)}`. No model in anything here.", "",
      "## The programs the agent shipped, directives removed, profiled before and after the fix", "",
      "A loop counts when DiscoPoP reports it as Do-All. \"Gain\": more loops reported after the fix than before; "
      "\"a loop withdrawn\": a loop reported before the fix and not after it.", "",
      "| programs of | changed programs | loops | reported before | reported after | programs that gain | of them: every loop reported | "
      "programs with a loop withdrawn |", "|---|---|---|---|---|---|---|---|"]
gains = collections.defaultdict(collections.Counter)
withdrawn = []
for part, label in PARTS:
    rows = [(before[k], after[k]) for k in sorted(before) if before[k]["part"] == part and before[k]["verdict"] == "profiled"]
    assert all(a["verdict"] == "profiled" for _, a in rows)
    gain = [(b, a) for b, a in rows if sum(a["doall"]) > sum(b["doall"])]
    lost = [(b, a) for b, a in rows if any(x and not y for x, y in zip(b["doall"], a["doall"]))]
    for b, a in gain:
        gains[label][(b["benchmark"].split("/")[1], b["harness_outcome"])] += 1
    withdrawn += [(label, b, a) for b, a in lost]
    md.append(f"| {label} | {len(rows)} | {sum(b['loops'] for b, _ in rows)} | {sum(sum(b['doall']) for b, _ in rows)} | "
              f"{sum(sum(a['doall']) for _, a in rows)} | {len(gain)} | {sum(1 for _, a in gain if all(a['doall']))} | {len(lost)} |")
md += ["", "**Where the gains are** (unit, the trial's outcome in its experiment: programs):", ""]
for label, c in gains.items():
    md.append(f"- {label}: " + "; ".join(f"`{u}` {o}: {n}" for (u, o), n in sorted(c.items())))
md += ["", "**Every loop withdrawn** — the loop over the index tables of `k53`, whose iterations feed each other. Before the fix "
       "it was reported Do-All when it stood after another loop inside the repetition loop (its iterations were not "
       "recorded, so the dependence between them looked like one inside a single iteration); the gate's race stage "
       "refused the directive in each of these trials:", ""]
for label, b, a in withdrawn:
    t = json.loads((campaign.RESULTS / b["trial"] / "trial.json").read_text())
    md.append(f"- {label}: `{b['benchmark'].split('/')[1]}` rep {b['repeat']} ({b['harness_outcome']}) — reported "
              f"{['yes' if x else 'no' for x in b['doall']]} → {['yes' if x else 'no' for x in a['doall']]}; gate failures "
              f"recorded in the trial: {t.get('gate_failures_phase_b') or t.get('gate_failures_d40')}")


def outcomes(run):
    out = {}
    for p in sorted(campaign.find_run(run).glob("benchmarks/tsvc_c2/*/discopop_capability/*/rep1/trial.json")):
        t = json.loads(p.read_text())
        out[t["benchmark"].split("/")[1]] = (t.get("outcome"), int(t.get("pragmas_in_final") or 0), int(t.get("llm_calls") or 0))
    return out


old = [outcomes(r) for r in ("t0_11_c2_a", "t0_11_c2_b", "t0_11_c2_c")]
new = [outcomes(r) for r in ("t0_11_c2_b14_a", "t0_11_c2_b14_b")]
names = sorted(old[0])
differ = [n for n in names if {o[n][:2] for o in old} != {w[n][:2] for w in new}]
tab = collections.Counter(new[0][n][0] for n in names)
md += ["", "## DiscoPoP alone on the 44 originals, fixed profiler (`t0_11_c2_b14_a`, `t0_11_c2_b14_b`)", "",
       f"{len(names)} packages in each draw, {sum(w[n][2] for w in new for n in names)} model calls. Packages whose "
       f"outcome or number of directives differs from the three draws before the fix (`t0_11_c2_a`–`c`): "
       f"**{len(differ)}**{(' — ' + ', '.join(differ)) if differ else ''}. Outcomes, draw a: "
       + ", ".join(f"{k} {v}" for k, v in sorted(tab.items())) + ".", ""]
(HERE / "b14_readout.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
