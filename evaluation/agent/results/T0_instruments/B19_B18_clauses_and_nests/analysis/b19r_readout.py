def answers(path, label):
    """The runs of one explorer in a log of repeat_explorer.py: [(number of runs, the answer's lines)]."""
    m = re.search(re.escape(label) + r": \d+ different answer\(s\) in (\d+) runs\n(.*?)(?=\n\S[^\n]*: \d+ different answer|\n\S[^\n]* run 1:|\Z)",
                  path.read_text(), re.S)
    if not m:
        return 0, []
    parts = re.split(r"--- answer #\d+ \((\d+) of \d+ runs\)\n", m.group(2))[1:]
    return int(m.group(1)), [(int(c), a.strip().splitlines()) for c, a in zip(parts[0::2], parts[1::2])]


