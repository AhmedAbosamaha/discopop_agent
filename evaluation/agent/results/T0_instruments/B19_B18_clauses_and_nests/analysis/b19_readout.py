"""DiscoPoP B19 and B18 repaired (explorer, 8 Oct 2026) — the regression check. No model in anything here. Reads

  runs/t0_11_c3_b19_a, _b, _c      DiscoPoP alone on the 44 tsvc_c3 packages, three draws, on the repaired explorer,
                                   against the three draws before the repairs (T0.18: t0_11_c3_a, _b, _c)
  runs/t0_11_b19_apps_a, _b, _c    DiscoPoP alone on the 31 packages outside TSVC, three draws, against the draws
                                   of 7 Oct (t0_11_b14_apps_a, _b, _c) and of 20 Sep (t0_11_classes_a, _b, _c)
  analysis/mac_explorer_runs/      the explorer before against the explorer after on ONE kept profile per package
                                   (Mac): the 44 tsvc_c3 packages in one run each, the 30 PolyBench packages in
                                   three runs each, seidel-2d in five more
  analysis/server_explorer_reports.json
                                   what the explorer reported on the profile each draw kept on the server (the loops
                                   called parallel, the reductions, the dependence that blocked each other loop),
                                   read there by analysis/server_explorer_reports.py; the profiles are not fetched

    venv/bin/python evaluation/agent/results/T0_instruments/B19_B18_clauses_and_nests/analysis/b19_readout.py
"""
import collections
import json
import os
import re
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
AGENT = HERE.parents[3]
sys.path.insert(0, str(AGENT / "tools"))
sys.path.insert(0, str(AGENT.parent / "shared"))
import campaign  # noqa: E402
import class_table  # noqa: E402

TS_NEW = ("t0_11_c3_b19_a", "t0_11_c3_b19_b", "t0_11_c3_b19_c")
TS_OLD = ("t0_11_c3_a", "t0_11_c3_b", "t0_11_c3_c")
AP_NEW = ("t0_11_b19_apps_a", "t0_11_b19_apps_b", "t0_11_b19_apps_c")
AP_OLD = ("t0_11_b14_apps_a", "t0_11_b14_apps_b", "t0_11_b14_apps_c")
AP_SEP = ("t0_11_classes_a", "t0_11_classes_b", "t0_11_classes_c")
PRAGMA = re.compile(r"#\s*pragma\s+omp\b.*")


def collect(runs):
    with tempfile.TemporaryDirectory(prefix="b19_") as tmp:
        for r in runs:
            os.symlink(campaign.find_run(r), Path(tmp) / r)
        return class_table.collect(list(runs), Path(tmp))


def draws(rec):
    return sorted((v["outcome"], int(v["pragmas"] or 0)) for v in rec["draws"].values())


def show(rec):
    return ", ".join(f"{a} ({b})" for a, b in draws(rec)) if rec else "—"


def offered(run, bench):
    """What DiscoPoP offered in one draw: every directive it wrote, with the line under it and the gate's verdict."""
    out = []
    for d in sorted(campaign.find_run(run).glob(f"benchmarks/{bench}/discopop_capability/*/rep1")):
        cj = d / "agent_patches" / "candidates.jsonl"
        for ln in (cj.read_text().splitlines() if cj.is_file() else []):
            if not ln.strip():
                continue
            c = json.loads(ln)
            patch = (d / "agent_patches" / c["patch"]).read_text().splitlines()
            for i, l in enumerate(patch):
                if l.startswith("+") and PRAGMA.search(l):
                    under = next((x[1:].strip() for x in patch[i + 1:] if x[:1] in " +" and x[1:].strip()), "")
                    out.append((PRAGMA.search(l).group(0).strip(), under, "kept" if c.get("stage") == "accepted" else f"refused at {c.get('stage')}"))
    return sorted(out)


def calls(runs):
    n = t = 0
    for r in runs:
        for p in campaign.find_run(r).glob("benchmarks/**/trial.json"):
            t += 1
            n += int(json.loads(p.read_text()).get("llm_calls") or 0)
    return t, n


md = ["# DiscoPoP B19 and B18 repaired — DiscoPoP alone before and after, on the server", "",
      "Generated by `analysis/b19_readout.py`. No model in anything here. Before: the explorer of commit `3d1b6b180` "
      "(the draws of T0.18 and of 7 Oct). After: the explorer of commit `855dd0093` (B19: a last value assigned in only "
      "some passes blocks Do-All, an array is shared, only a loop's own units decide its clauses; B18: a write-after-read "
      "is attached to units by its own roles). The profiler is the same build in both."]

# ---- (1) TSVC -------------------------------------------------------------------------------------------------
cn, co = collect(TS_NEW), collect(TS_OLD)
kern = sorted(k.split("/")[1] for k in cn)
assert kern == sorted(k.split("/")[1] for k in co) and len(kern) == 44, "not the 44 tsvc_c3 packages in both"
key = "tsvc_c3/{}".format
cls_diff = [k for k in kern if cn[key(k)]["class"] != co[key(k)]["class"]]
draw_diff = [k for k in kern if draws(cn[key(k)]) != draws(co[key(k)])]
unstable = [k for k in kern if len({v["outcome"] for v in cn[key(k)]["draws"].values()}) > 1]
off_new = {k: [offered(r, key(k)) for r in TS_NEW] for k in kern}
off_old = {k: [offered(r, key(k)) for r in TS_OLD] for k in kern}
off_diff = [k for k in kern if sorted(map(json.dumps, off_new[k])) != sorted(map(json.dumps, off_old[k]))]
tot_n, tot_o = (collections.Counter(r["class"] for r in c.values()) for c in (cn, co))
t_new, c_new = calls(TS_NEW)
md += ["", "## 1 The 44 `tsvc_c3` packages, three draws (`t0_11_c3_b19_a`, `t0_11_c3_b19_b`, `t0_11_c3_b19_c`)", "",
       f"{t_new} trials, {c_new} model calls. Classes after: " + ", ".join(f"{k} {v}" for k, v in sorted(tot_n.items()))
       + "; before (`t0_11_c3_a`, `_b`, `_c`): " + ", ".join(f"{k} {v}" for k, v in sorted(tot_o.items())) + ".", "",
       f"**Packages whose class differs: {len(cls_diff)}**" + ((" — " + ", ".join(f"`{k}`" for k in cls_diff)) if cls_diff else "")
       + f". Packages whose outcome or number of kept directives differs in any draw: {len(draw_diff)}"
       + ((" — " + ", ".join(f"`{k}`" for k in draw_diff)) if draw_diff else "")
       + f". **Packages for which DiscoPoP offers other directives (text, loop or the gate's verdict) in any draw: {len(off_diff)}**"
       + ((" — " + ", ".join(f"`{k}`" for k in off_diff)) if off_diff else "")
       + f". Packages whose three draws after the repairs do not agree with each other: {len(unstable)}"
       + ((" — " + ", ".join(f"`{k}`" for k in unstable)) if unstable else "") + ".", ""]
md += ["| package | class before | after | draws before (outcome, kept directives) | draws after | median speed-up before | after |", "|---|---|---|---|---|---|---|"]
for k in kern:
    o, n = co[key(k)], cn[key(k)]
    if o["class"] == "A" or n["class"] == "A" or k in draw_diff or k in off_diff:
        md.append(f"| `{k}` | {o['class']} | {n['class']} | {show(o)} | {show(n)} | "
                  f"{(str(o['median_speedup']) + '×') if o['median_speedup'] else '—'} | {(str(n['median_speedup']) + '×') if n['median_speedup'] else '—'} |")
md += ["", "(Shown: every package of class A before or after and every package with a difference; every other package is "
       "`no-change` with no directive in all six draws.)", ""]
for k in off_diff:
    md += [f"**`{k}` — what DiscoPoP offered** (directive · the line under it · the gate), one line per draw:", ""]
    for name, runs, off in (("before", TS_OLD, off_old), ("after", TS_NEW, off_new)):
        for r, o in zip(runs, off[k]):
            md.append(f"- {name}, `{r}`: " + ("; ".join(f"`{p}` on `{u}` — {v}" for p, u, v in o) if o else "nothing offered"))
    md.append("")

# ---- (2) the packages outside TSVC ----------------------------------------------------------------------------
an, ao, asep = collect(AP_NEW), collect(AP_OLD), collect(AP_SEP)
apps = sorted(an)
assert apps == sorted(ao) and len(apps) == 31, "not the 31 packages in both"
t_new, c_new = calls(AP_NEW)


def best(rec):
    sp = [v.get("speedup") for v in rec["draws"].values() if v.get("speedup") and int(v.get("pragmas") or 0) > 0]
    return (f"{min(sp):.1f}–{max(sp):.1f}×" if len(sp) > 1 else f"{sp[0]:.1f}×") if sp else "—"


moved = [k for k in apps if draws(an[k]) != draws(ao[k])]
back = [k for k in moved if k in asep and draws(an[k]) == draws(asep[k])]
md += ["## 2 The 31 packages outside TSVC, three draws (`t0_11_b19_apps_a`, `t0_11_b19_apps_b`, `t0_11_b19_apps_c`)", "",
       f"{t_new} trials, {c_new} model calls. Against the three draws of 7 Oct on the explorer before the repairs "
       "(`t0_11_b14_apps_a`–`c`) and the three of 20 Sep (`t0_11_classes_a`–`c`, before the explorer fixes of 26–27 Sep). "
       "On these programs the explorer's verdict differs between runs on one profile (B21), so a package is read by "
       "its three draws, not by one.", "",
       f"**Packages whose three draws differ from 7 Oct's: {len(moved)}** — " + (", ".join(f"`{k}`" for k in moved) or "none")
       + f". Of these, with the same three draws as on 20 Sep: {len(back)}" + ((" — " + ", ".join(f"`{k}`" for k in back)) if back else "") + ".", "",
       "| package | 20 Sep (outcome, kept directives) | 7 Oct, before the repairs | 8 Oct, after | speed-up 20 Sep | 7 Oct | 8 Oct |", "|---|---|---|---|---|---|---|"]
for k in apps:
    s_ = asep.get(k)
    md.append(f"| `{k}`{'' if k not in moved else ' ←'} | {show(s_)} | {show(ao[k])} | {show(an[k])} | {best(s_) if s_ else '—'} | {best(ao[k])} | {best(an[k])} |")
md += ["", "(← : the three draws differ from 7 Oct's.)", ""]


def loops_offered(run, bench):
    """The loops DiscoPoP offered a directive for in one draw, each with the gate's verdict (the clauses left out: their
    order differs between runs)."""
    return sorted((u, v) for _, u, v in offered(run, bench))


def grouped(runs, bench):
    by = collections.OrderedDict()
    for r in runs:
        try:
            key = "; ".join(f"`{u}` — {v}" for u, v in loops_offered(r, bench)) or "nothing offered"
        except KeyError:
            key = "(no such trial)"
        by.setdefault(key, []).append(r.rsplit("_", 1)[1])
    return by


off_moved = [k for k in apps if any(loops_offered(r, k) != loops_offered(AP_OLD[0], k) for r in AP_OLD + AP_NEW)]
unst_old = [k for k in apps if any(loops_offered(r, k) != loops_offered(AP_OLD[0], k) for r in AP_OLD)]
unst_new = [k for k in apps if any(loops_offered(r, k) != loops_offered(AP_NEW[0], k) for r in AP_NEW)]
md += ["### 2.1 What DiscoPoP offered, loop by loop", "",
       f"Packages in which the loops offered or the gate's verdicts are not the same in all six draws (7 Oct and 8 Oct): "
       f"**{len(off_moved)} of {len(apps)}**. Packages whose three draws do not agree with each other: {len(unst_old)} on 7 Oct "
       f"({', '.join(f'`{k}`' for k in unst_old)}), {len(unst_new)} on 8 Oct ({', '.join(f'`{k}`' for k in unst_new)}).", ""]
for k in off_moved:
    md.append(f"**`{k}`**")
    md.append("")
    for name, runs in (("20 Sep", AP_SEP), ("7 Oct", AP_OLD), ("8 Oct", AP_NEW)):
        if name == "20 Sep" and k not in asep:
            continue
        for what, ds in grouped(runs, k).items():
            md.append(f"- {name}, draw{'s' if len(ds) > 1 else ''} {', '.join(ds)}: {what}")
    md.append("")

# ---- (2.2) what the explorer reported on each draw's profile ----------------------------------------------------
SRV = HERE / "server_explorer_reports.json"
if SRV.is_file():
    srv = json.loads(SRV.read_text())

    def observed(run, bench):
        """The loops blocked on a dependence the profiler observed in the run (a record with a call path)."""
        return frozenset(b[0] for b in srv[run][bench]["blocked"] if b[3] == "DYNAMIC_ANALYSIS")

    def states(runs, bench):
        sets = [observed(r, bench) for r in runs]
        vary = frozenset().union(*sets) - frozenset.intersection(*sets)
        return sets, vary, ["all" if s & vary == vary else ("none" if not s & vary else "part") for s in sets] if vary else None

    md += ["### 2.2 What the explorer reported on each draw's own profile", "",
           "Read on the server from each draw's kept profile (`analysis/server_explorer_reports.json`): the number of loops "
           "blocked on a dependence the profiler OBSERVED in the run, and the number of loops called parallel (Do-All), "
           "per draw. Every profiled run printed the runtime's loop-results line (so this is not B17).", "",
           "| package | 7 Oct a | b | c | 8 Oct a | b | c | reading |", "|---|---|---|---|---|---|---|---|"]
    tally = {"7 Oct": collections.Counter(), "8 Oct": collections.Counter()}
    part = []
    for k in apps:
        cells, notes = [], []
        for name, runs in (("7 Oct", AP_OLD), ("8 Oct", AP_NEW)):
            sets, vary, st = states(runs, k)
            cells += [f"{len(s)} / {len(srv[r][k]['do_all'])}" for s, r in zip(sets, runs)]
            if st is None:
                tally[name]["same, some loop blocked" if sets[0] else "same, no loop blocked"] += 1
            else:
                tally[name]["varies"] += 1
                tally[name]["draws with all"] += st.count("all")
                tally[name]["draws with none"] += st.count("none")
                part += [(name, k)] * st.count("part")
                notes.append(f"{name}: the same {len(vary)} loop(s) blocked in {st.count('all')} draw(s) and none of them in {st.count('none')}")
        md.append(f"| `{k}` | " + " | ".join(cells) + f" | {'; '.join(notes)} |")
    md += ["", "(Cell: loops blocked on an observed dependence / loops called parallel.)", ""]
    for name in ("7 Oct", "8 Oct"):
        t = tally[name]
        md.append(f"- **{name}:** {t['varies']} of {len(apps)} packages differ between their three draws — over these, "
                  f"{t['draws with all']} draws block every one of the loops in question and {t['draws with none']} block none of them; "
                  f"{t['same, no loop blocked']} packages have no loop blocked on an observed dependence in any of the three draws, "
                  f"{t['same, some loop blocked']} have the same blocked loops in all three.")
    md += ["", f"Draws that block SOME of the loops in question and not others: {len(part)}"
           + (" — " + ", ".join(f"`{k}` ({n})" for n, k in part) if part else "") + ". So where a package's draws differ, "
           "the explorer has either every dependence-blocked loop or none of them — all or nothing, per run.", ""]
    ts = [k for k in kern if not all(
        (srv[r][key(k)]["do_all"], srv[r][key(k)]["reduction"], sorted({(b[0], b[1]) for b in srv[r][key(k)]["blocked"]}))
        == (srv[TS_NEW[0]][key(k)]["do_all"], srv[TS_NEW[0]][key(k)]["reduction"], sorted({(b[0], b[1]) for b in srv[TS_NEW[0]][key(k)]["blocked"]}))
        for r in TS_NEW)]
    tv = [k for k in kern if not all(sorted({(b[0], b[1], b[2]) for b in srv[r][key(k)]["blocked"]})
                                     == sorted({(b[0], b[1], b[2]) for b in srv[TS_NEW[0]][key(k)]["blocked"]}) for r in TS_NEW)]
    md += [f"**The 44 `tsvc_c3` packages, the same reading of the three draws after the repairs:** packages whose draws do not "
           f"agree in the loops called parallel, the reductions, the blocked loops or the type of the dependence that blocks "
           f"each: **{len(ts)}**. Packages in which the VARIABLE a blocker record names differs between draws (a record "
           f"names one of the dependences that block the loop): {len(tv)} of 44.", ""]

