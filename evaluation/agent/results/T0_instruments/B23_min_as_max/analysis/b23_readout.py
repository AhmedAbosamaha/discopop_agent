#!/usr/bin/env python3
"""DiscoPoP B23 repaired (profiler and explorer, 10 Oct 2026, commit c89952852) — the regression check. No model. Reads

  runs/t0_11_c3_b23_a, _b, _c       DiscoPoP alone on the 44 tsvc_c3 packages, three draws, on the repaired DiscoPoP,
                                    against the last three draws before it (t0_11_c3_b19r_a, _b, _c)
  runs/t0_11_c4_b23_a, _b, _c       the same on the 9 tsvc_c4 packages, against T0.19's draws (t0_11_c4_a, _b, _c)
  runs/t0_11_b23_apps_a, _b, _c     the same on the 31 packages outside TSVC, against t0_11_b19r_apps_a, _b, _c
  analysis/reduction_files_before.txt, reduction_files_after.txt
                                    the operations in every package's reduction file, from the profiles the first
                                    draw of each set kept on the server (analysis/reduction_files_scan.sh)

    venv/bin/python evaluation/agent/results/T0_instruments/B23_min_as_max/analysis/b23_readout.py
"""
import collections
import json
import os
import re
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
AGENT = HERE.parents[3]
sys.path.insert(0, str(AGENT / "tools"))
sys.path.insert(0, str(AGENT.parent / "shared"))
import campaign  # noqa: E402
import class_table  # noqa: E402

SETS = [  # title, suite prefix or None, new draws, old draws, expected number of packages
    ("The 44 `tsvc_c3` packages", ("t0_11_c3_b23_a", "t0_11_c3_b23_b", "t0_11_c3_b23_c"),
     ("t0_11_c3_b19r_a", "t0_11_c3_b19r_b", "t0_11_c3_b19r_c"), 44),
    ("The 9 `tsvc_c4` packages", ("t0_11_c4_b23_a", "t0_11_c4_b23_b", "t0_11_c4_b23_c"),
     ("t0_11_c4_a", "t0_11_c4_b", "t0_11_c4_c"), 9),
    ("The 31 packages outside TSVC", ("t0_11_b23_apps_a", "t0_11_b23_apps_b", "t0_11_b23_apps_c"),
     ("t0_11_b19r_apps_a", "t0_11_b19r_apps_b", "t0_11_b19r_apps_c"), 31),
]
PRAGMA = re.compile(r"#\s*pragma\s+omp\b.*")
CLAUSE = re.compile(r"(\w+)\(([^)]*)\)")


def collect(runs):
    with tempfile.TemporaryDirectory(prefix="b23_") as tmp:
        for r in runs:
            os.symlink(campaign.find_run(r), Path(tmp) / r)
        return class_table.collect(list(runs), Path(tmp))


def draws(rec):
    return sorted((v["outcome"], int(v["pragmas"] or 0)) for v in rec["draws"].values())


def offered(run, bench):
    """What DiscoPoP offered in one draw: (the line under the directive, its clauses as sorted sets, the gate's
    verdict) — the order of the names in a clause differs between runs and is not compared."""
    out = []
    for d in sorted(campaign.find_run(run).glob(f"benchmarks/{bench}/discopop_capability/*/rep1")):
        cj = d / "agent_patches" / "candidates.jsonl"
        for ln in (cj.read_text().splitlines() if cj.is_file() else []):
            if not ln.strip():
                continue
            c = json.loads(ln)
            patch = (d / "agent_patches" / c["patch"]).read_text().splitlines()
            for i, l in enumerate(patch):
                if l.startswith("+") and PRAGMA.search(l):
                    under = next((x[1:].strip() for x in patch[i + 1:] if x[:1] in " +" and x[1:].strip()), "")
                    text = PRAGMA.search(l).group(0)
                    clauses = " ".join(f"{k}({', '.join(sorted(x.strip() for x in v.split(',')))})"
                                       for k, v in sorted(CLAUSE.findall(text)))
                    out.append((under, clauses, "kept" if c.get("stage") == "accepted" else f"refused at {c.get('stage')}"))
    return sorted(out)


def reductions(runs, bench):
    """Every reduction clause DiscoPoP offered for a package over the given draws, as (loop line, clause) pairs."""
    got = set()
    for r in runs:
        for under, clauses, _ in offered(r, bench):
            for m in re.finditer(r"reduction\(([^)]*)\)", clauses):
                got.add((under, m.group(0)))
    return got


def calls(runs):
    n = t = 0
    for r in runs:
        for p in campaign.find_run(r).glob("benchmarks/**/trial.json"):
            t += 1
            n += int(json.loads(p.read_text()).get("llm_calls") or 0)
    return f"{t} trials, {n} model calls"


def show(rec):
    return ", ".join(f"{a} ({b})" for a, b in draws(rec))


md = ["# DiscoPoP B23 repaired — DiscoPoP alone before and after, on the server", "",
      "Generated by `analysis/b23_readout.py`. No model in anything here. Before: the DiscoPoP of the last draws before "
      "the repair. After: commit `c89952852` — the profiler reads minimum or maximum from the stored call, the explorer "
      "records the reduction entry that matched the loop; the profiler rebuilt on the server from that commit.", ""]
verdict = []
for n, (title, new, old, expect) in enumerate(SETS, 1):
    cn, co = collect(new), collect(old)
    names = sorted(cn)
    assert names == sorted(co) and len(names) == expect, f"{title}: {len(cn)} and {len(co)} packages, expected {expect}"
    cls_diff = [k for k in names if cn[k]["class"] != co[k]["class"]]
    draw_diff = [k for k in names if draws(cn[k]) != draws(co[k])]
    off_diff = [k for k in names if sorted(json.dumps(offered(r, k)) for r in new) != sorted(json.dumps(offered(r, k)) for r in old)]
    red_diff = [k for k in names if reductions(new, k) != reductions(old, k)]
    tot_n, tot_o = (collections.Counter(r["class"] for r in c.values()) for c in (cn, co))
    md += [f"## {n} {title}, three draws ({', '.join('`' + r + '`' for r in new)})", "",
           f"{calls(new)}. Against {', '.join('`' + r + '`' for r in old)}. Classes after: "
           + ", ".join(f"{k} {v}" for k, v in sorted(tot_n.items())) + "; before: "
           + ", ".join(f"{k} {v}" for k, v in sorted(tot_o.items())) + ".", "",
           f"**Packages whose class differs: {len(cls_diff)}**" + ((" — " + ", ".join(f"`{k}`" for k in cls_diff)) if cls_diff else "")
           + f". Packages whose outcome or number of kept directives differs in any draw: {len(draw_diff)}"
           + ((" — " + ", ".join(f"`{k}`" for k in draw_diff)) if draw_diff else "")
           + f". Packages for which DiscoPoP offers other directives (loop, clauses or the gate's verdict) in any draw: {len(off_diff)}"
           + ((" — " + ", ".join(f"`{k}`" for k in off_diff)) if off_diff else "")
           + f". **Packages whose reduction clauses differ (the loop or the operation), over the three draws: {len(red_diff)}**"
           + ((" — " + ", ".join(f"`{k}`" for k in red_diff)) if red_diff else "") + ".", ""]
    verdict.append((title, len(cls_diff), len(red_diff)))
    for k in sorted(set(cls_diff + draw_diff + off_diff + red_diff)):
        md.append(f"**`{k}`** — class before {co[k]['class']}, after {cn[k]['class']}; draws before: {show(co[k])}; after: {show(cn[k])}")
        for name, runs in (("before", old), ("after", new)):
            by = collections.OrderedDict()
            for r in runs:
                what = "; ".join(f"`{u}` [{c or 'no clause'}] — {v}" for u, c, v in offered(r, k)) or "nothing offered"
                by.setdefault(what, []).append(r.rsplit("_", 1)[1])
            for what, ds in by.items():
                md.append(f"- {name}, draw{'s' if len(ds) > 1 else ''} {', '.join(ds)}: {what}")
        md.append("")
    ops = collections.Counter()
    for k in names:
        for _, clause in reductions(new, k):
            ops[re.match(r"reduction\(\s*([^:\s]+)", clause).group(1)] += 1
    md += ["Reduction clauses offered after the repair, by operation (a clause counted once per package and loop): "
           + (", ".join(f"`{k}` {v}" for k, v in sorted(ops.items())) or "none") + ".", ""]

# ---- the reduction files ---------------------------------------------------------------------------------------------
def scan(path):
    out = {}
    for ln in path.read_text().splitlines():
        if ln.startswith("==") or "|" not in ln:
            continue
        run, pkg, _, ops = [x.strip() for x in ln.split("|")]
        out[pkg.replace("profiles/", "")] = ops
    return out


bf, af = HERE / "reduction_files_before.txt", HERE / "reduction_files_after.txt"
if bf.is_file() and af.is_file():
    b, a = scan(bf), scan(af)
    assert sorted(a) == sorted(b), "the two scans do not hold the same packages"
    changed = [k for k in sorted(a) if a[k] != b[k]]
    with_lt = [k for k in sorted(a) if "<" in a[k]]
    md += [f"## {len(SETS) + 1} The reduction file of every package, before and after", "",
           f"{len(a)} packages. Packages whose file holds other operations after the repair: **{len(changed)}**"
           + ((" — " + "; ".join(f"`{k}`: {b[k]} → {a[k]}" for k in changed)) if changed else "")
           + f". Packages with a minimum entry (`<`) after the repair: **{len(with_lt)}**"
           + ((" — " + ", ".join(f"`{k}`" for k in with_lt)) if with_lt else "") + ".", ""]
md += ["## Verdict", ""] + [f"- {t}: {c} package(s) with another class, {r} with other reduction clauses." for t, c, r in verdict] + [""]
(HERE / "b23_readout.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
