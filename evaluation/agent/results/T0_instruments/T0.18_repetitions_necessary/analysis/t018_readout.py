#!/usr/bin/env python3
"""T0.18 — is a tsvc_c3 package (packaging v7: every repetition necessary) the program its tsvc_c2 package (v6)
is? No model in anything here. Reads

  build/                      the generator's validation log and the digest of every package file, Mac and server
  preflight/t0_1_c3_sizes     the sizes, against the tsvc_c2 entries of config/kernel_sizes.json (t0_1_c2_sizes)
  checks/t0_18_server_a, _b   two draws of tools/layout_equivalence.py --old tsvc_c2 --new tsvc_c3 --added-values 2
  preflight/t0_11_c3_a, b, c  DiscoPoP alone in three draws, against the three draws of tsvc_c2 on the same
                              DiscoPoP (t0_11_c2_b14_a, _b, _c)
  preflight/t0_14_c3_refs     the 28 expert references through the harness, against t0_14_c2_refs

    venv/bin/python evaluation/agent/results/T0_instruments/T0.18_repetitions_necessary/analysis/t018_readout.py
"""
import collections
import json
import os
import re
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
GROUP = HERE.parent
AGENT = HERE.parents[3]
sys.path.insert(0, str(AGENT / "tools"))
sys.path.insert(0, str(AGENT.parent / "shared"))
import campaign  # noqa: E402
import class_table  # noqa: E402

CRITERIA = [("candidates", "candidates (tier, pattern)"), ("do_all", "Do-All set"),
            ("blocker", "blocker of the loop under study"), ("repetition", "repetition loop"),
            ("statement", "order statement (version 4)")]
CHANGED_FILE = ("s3112", "s313", "s331")          # the benchmark's file differs from v6's: the `dummy` call
md = ["# T0.18 — packaging v7 (`tsvc_c3`) against packaging v6 (`tsvc_c2`) on the server", "",
      "Generated by `analysis/t018_readout.py`. No model in anything here. DiscoPoP is the fixed build (defect B14)."]

# ---- (1) the packages -------------------------------------------------------------------------------------
B = HERE / "build"


def digests(name):
    return {ln.split()[1]: ln.split()[0] for ln in (B / name).read_text().splitlines() if ln.strip()}


mac, srv = digests("mac_digests.txt"), digests("server_digests.txt")
differ = sorted(k for k in set(mac) | set(srv) if mac.get(k) != srv.get(k))
logs = {m: (B / f"{m}_build.log").read_text() for m in ("mac", "server")}
ok = {m: len(re.findall(r" OK$", t, re.M)) for m, t in logs.items()}
failed = {m: t.count("FAILED") for m, t in logs.items()}
metas = sorted((AGENT / "prepared" / "tsvc_c3").glob("*/meta.json"))
not_proven = {json.loads(p.read_text())["kernel"]: json.loads(p.read_text()).get("repetitions_note", "one repetition")
              for p in metas if not json.loads(p.read_text()).get("repetitions_proven")}
pass_digest = sorted({ln.split()[0][:12] for ln in (B / "server_pass_digest.txt").read_text().splitlines() if ln.strip()})
git_status = (B / "server_git_status.txt").read_text().strip()
md += ["", "## 1 The packages", "",
       f"`prepare_tsvc.py --layout v7 --suite tsvc_c3 --validate`: Mac {ok['mac']} validated, {failed['mac']} failed; server "
       f"{ok['server']} validated, {failed['server']} failed. Files compared by sha256 (every file of every package and "
       f"every measurement header outside the packages): {len(mac)} on the Mac, {len(srv)} on the server, "
       f"**{len(differ)} differ**{(' — ' + ', '.join(differ[:6])) if differ else ''}. Tracked files changed by the build "
       f"on the server (`git status`): {'none' if not git_status else git_status}. The server's profiler pass: "
       f"`{', '.join(pass_digest)}`.", "",
       f"Repetitions proven necessary: {len(metas) - len(not_proven)} of {len(metas)} packages. Declared not provable: "
       + "; ".join(f"`{k}` ({v[:60].rstrip()}{'…' if len(v) > 60 else ''})" for k, v in sorted(not_proven.items())) + "."]

# ---- (2) sizes --------------------------------------------------------------------------------------------
new = json.loads((campaign.find_run("t0_1_c3_sizes") / "chosen.json").read_text())
table = json.loads((AGENT / "config" / "kernel_sizes.json").read_text())["kernels"]
rows, same = [], 0
for key in sorted(new["kernels"]):
    n = new["kernels"][key]
    o = table.get(key.replace("tsvc_c3/", "tsvc_c2/"))
    eq = o is not None and (o["timing_size"], o["verification_size"]) == (n["timing_size"], n["verification_size"])
    same += eq
    rows.append((key.split("/")[1], o, n, eq))
md += ["", "## 2 Sizes (`t0_1_c3_sizes`)", "",
       f"Measured {new['started']} to {new['finished']} on `{new['host']}` (load at start {new['load_start']}). "
       f"Timing size and verification size equal to the `tsvc_c2` package's: **{same} of {len(rows)}**.", ""]
if same != len(rows):
    md += ["| package | v6 timing / verification (longest measured) | v7 timing / verification (longest measured) |", "|---|---|---|"]
    for name, o, n, eq in rows:
        if not eq:
            def show(x):
                return "—" if x is None else (f"{x['timing_size']} / {x['verification_size']} "
                                              f"({x['longest_measured']['size']}: {x['longest_measured']['kernel_s']:.3f} s)")
            md.append(f"| `{name}` | {show(o)} | {show(n)} |")
    md.append("")
ratios = sorted((n["longest_measured"]["kernel_s"] / o["longest_measured"]["kernel_s"], name) for name, o, n, eq in rows
                if o and o["longest_measured"]["size"] == n["longest_measured"]["size"])
if ratios:
    md.append(f"Sequential kernel time at the longest size measured, v7 / v6 (the {len(ratios)} packages measured at the "
              f"same longest size): median {ratios[len(ratios) // 2][0]:.3f}, from {ratios[0][0]:.3f} (`{ratios[0][1]}`) to "
              f"{ratios[-1][0]:.3f} (`{ratios[-1][1]}`).")

# ---- (3) DiscoPoP's view -----------------------------------------------------------------------------------
md += ["", "## 3 DiscoPoP's view, two draws (`t0_18_server_a`, `t0_18_server_b`)", "",
       "`layout_equivalence.py --old tsvc_c2 --new tsvc_c3 --added-values 2`. Output: the full dump on the shipped and "
       "the perturbed input with v7's last two lines left out, byte for byte.", "",
       "| draw | packages | output the same | " + " | ".join(label for _, label in CRITERIA) + " | RAW flows with their carrier | order statement replayed, version 4 |",
       "|---|---|---|" + "---|" * (len(CRITERIA) + 2)]
per_draw = {}
for d in ("a", "b"):
    root = campaign.find_run(f"t0_18_server_{d}")
    recs = {p.stem: json.loads(p.read_text()) for p in sorted(root.glob("*.json")) if p.name != "ARCHIVE.json"}
    per_draw[d] = recs
    errors = [n for n, r in recs.items() if not r.get("same")]
    replay = (root / "order_replay.md").read_text()
    v4 = re.search(r"^Version 4: (\d+) right, (\d+) wrong", replay, re.M)
    profiles = re.search(r"^(\d+) profiles\.", replay, re.M)
    cells = [f"{sum(1 for r in recs.values() if r.get('same', {}).get(k))} of {len(recs)}" for k, _ in CRITERIA]
    md.append(f"| {d} | {len(recs)}{(' (' + str(len(errors)) + ' profile errors)') if errors else ''} | "
              f"{sum(1 for r in recs.values() if r['output_identical'])} of {len(recs)} | " + " | ".join(cells)
              + f" | {sum(1 for r in recs.values() if r.get('flows_same'))} of {len(recs)} | "
              + (f"{v4.group(1)} right, {v4.group(2)} wrong of {profiles.group(1)} profiles" if v4 and profiles else "not found") + " |")
names = sorted(per_draw["a"])
assert names == sorted(per_draw["b"])
out_diff = {d: [n for n in names if not per_draw[d][n]["output_identical"]] for d in "ab"}
md += ["", "Output differs: draw a — " + (", ".join(f"`{n}`" for n in out_diff["a"]) or "none") + "; draw b — "
       + (", ".join(f"`{n}`" for n in out_diff["b"]) or "none") + " (`s331` has other data by design)."]
both = collections.defaultdict(list)
for key, label in CRITERIA:
    da = [n for n in names if not per_draw["a"][n].get("same", {}).get(key, False)]
    db = [n for n in names if not per_draw["b"][n].get("same", {}).get(key, False)]
    if da or db:
        md.append(f"- {label}: differs in draw a on " + (", ".join(f"`{n}`" for n in da) or "none") + "; in draw b on "
                  + (", ".join(f"`{n}`" for n in db) or "none") + ".")
    for n in sorted(set(da) & set(db)):
        both[n].append(label)
md += ["", "**Packages that differ on a criterion in BOTH draws: " + (", ".join(f"`{n}` ({'; '.join(v)})" for n, v in sorted(both.items())) or "none") + ".**"]
for d in "ab":
    for n in names:
        r = per_draw[d][n]
        for key, label in CRITERIA:
            if r.get("same") and not r["same"][key]:
                md.append(f"- draw {d}, `{n}`, {label}: v6 `{r['views']['old'][key]}` — v7 `{r['views']['new'][key]}`")
flows = {d: [n for n in names if per_draw[d][n].get("same") and not per_draw[d][n]["flows_same"]] for d in "ab"}
md += ["", "RAW flows with their carrier (reported, not a criterion) differ: draw a — " + (", ".join(f"`{n}`" for n in flows["a"]) or "none")
       + "; draw b — " + (", ".join(f"`{n}`" for n in flows["b"]) or "none") + ".",
       "", "The three packages whose benchmark file differs from v6's (the call hands `dummy` the loop's result):", ""]
for n in CHANGED_FILE:
    line = []
    for d in "ab":
        r = per_draw[d][n]
        raw = {tuple(f) for c in r["new"]["candidates"] for f in c["flows"] if "dummy(" in f[1] or "dummy(" in f[2]}
        line.append(f"draw {d}: output {'the same' if r['output_identical'] else 'differs'}, the five criteria "
                    + ("the same" if all(r["same"].values()) else "DIFFER: " + ", ".join(k for k, v in r["same"].items() if not v))
                    + f", {len(raw)} RAW record(s) into the `dummy` call in the profile")
    md.append(f"- `{n}` — " + "; ".join(line))

# ---- (4) classes --------------------------------------------------------------------------------------------
NEW_RUNS = ("t0_11_c3_a", "t0_11_c3_b", "t0_11_c3_c")
OLD_RUNS = ("t0_11_c2_b14_a", "t0_11_c2_b14_b", "t0_11_c2_b14_c")
with tempfile.TemporaryDirectory(prefix="t018_") as tmp:
    for r in NEW_RUNS + OLD_RUNS:
        os.symlink(campaign.find_run(r), Path(tmp) / r)
    cn = class_table.collect(list(NEW_RUNS), Path(tmp))
    co = class_table.collect(list(OLD_RUNS), Path(tmp))


def draws(rec):
    return sorted((v["outcome"], int(v["pragmas"] or 0)) for v in rec["draws"].values())


calls = 0
for r in NEW_RUNS:
    for p in campaign.find_run(r).glob("benchmarks/**/trial.json"):
        calls += int(json.loads(p.read_text()).get("llm_calls") or 0)
kern = sorted(k.split("/")[1] for k in cn)
assert kern == sorted(k.split("/")[1] for k in co), "the two suites do not hold the same packages"
cls_diff = [k for k in kern if cn[f"tsvc_c3/{k}"]["class"] != co[f"tsvc_c2/{k}"]["class"]]
draw_diff = [k for k in kern if draws(cn[f"tsvc_c3/{k}"]) != draws(co[f"tsvc_c2/{k}"])]
tot_n = collections.Counter(r["class"] for r in cn.values())
tot_o = collections.Counter(r["class"] for r in co.values())
unstable = [k for k in kern if len({v["outcome"] for v in cn[f"tsvc_c3/{k}"]["draws"].values()}) > 1]
md += ["", "## 4 Classes: DiscoPoP alone in three draws (`t0_11_c3_a`, `t0_11_c3_b`, `t0_11_c3_c`)", "",
       f"{len(kern)} packages, {sum(r['draws_total'] for r in cn.values())} trials, {calls} model calls. Classes on v7: "
       + ", ".join(f"{k} {v}" for k, v in sorted(tot_n.items())) + "; on v6, same DiscoPoP (`t0_11_c2_b14_a`, `_b`, `_c`): "
       + ", ".join(f"{k} {v}" for k, v in sorted(tot_o.items())) + ".",
       "", f"**Packages whose class differs from v6's: {len(cls_diff)}**" + ((" — " + ", ".join(f"`{k}`" for k in cls_diff)) if cls_diff else "")
       + f". Packages whose outcome or number of directives differs in any draw: {len(draw_diff)}"
       + ((" — " + ", ".join(f"`{k}`" for k in draw_diff)) if draw_diff else "")
       + f". Packages whose three v7 draws do not agree with each other: {len(unstable)}"
       + ((" — " + ", ".join(f"`{k}`" for k in unstable)) if unstable else "") + ".", ""]
md += ["| package | class v6 | class v7 | v6 draws (outcome, directives) | v7 draws (outcome, directives) | DiscoPoP alone, median speed-up v6 | v7 |", "|---|---|---|---|---|---|---|"]
for k in kern:
    o, n = co[f"tsvc_c2/{k}"], cn[f"tsvc_c3/{k}"]
    if o["class"] == "A" or n["class"] == "A" or k in draw_diff or k in CHANGED_FILE:
        def show(rec):
            return ", ".join(f"{a} ({b})" for a, b in draws(rec))
        md.append(f"| `{k}` | {o['class']} | {n['class']} | {show(o)} | {show(n)} | "
                  f"{(str(o['median_speedup']) + '×') if o['median_speedup'] else '—'} | {(str(n['median_speedup']) + '×') if n['median_speedup'] else '—'} |")
md += ["", "(Shown: every package of class A on either packaging, every package with a difference, and the three "
       "whose benchmark file differs from v6's; every other package is `no-change` with no directive in all six draws.)"]

# ---- (5) references ------------------------------------------------------------------------------------------


def refs(run, suite):
    out = {}
    for p in sorted(campaign.find_run(run).glob(f"benchmarks/{suite}/*/expert_openmp/*/rep*/trial.json")):
        t = json.loads(p.read_text())
        v = t.get("verify") or {}
        sp = [x.get("speedup") for x in (v.get("par") or {}).values() if x.get("speedup")]
        out[t["benchmark"].split("/")[1]] = {"outcome": t.get("outcome"), "best": max(sp) if sp else None,
                                             "exact": (v.get("dump_exact"), v.get("dump_exact_seeded")),
                                             "err": max(float(v.get("dump_max_rel_err") or 0), float(v.get("dump_seeded_max_rel_err") or 0)),
                                             "size": v.get("verify_size"), "status": v.get("status")}
    return out


rn, ro = refs("t0_14_c3_refs", "tsvc_c3"), refs("t0_14_c2_refs", "tsvc_c2")
assert sorted(rn) == sorted(ro), "the two reference runs do not hold the same references"
out_n = collections.Counter(r["outcome"] for r in rn.values())
changed = [k for k in sorted(rn) if rn[k]["outcome"] != ro[k]["outcome"]]
inexact = [k for k in sorted(rn) if not all(rn[k]["exact"])]
ratio = sorted((rn[k]["best"] / ro[k]["best"], k) for k in rn if rn[k]["best"] and ro[k]["best"])
md += ["", "## 5 The expert references through the harness (`t0_14_c3_refs`)", "",
       f"{len(rn)} references, threads 6 and 12. Outcomes on v7: " + ", ".join(f"{k} {v}" for k, v in sorted(out_n.items()))
       + f". **Outcome differs from v6's (`t0_14_c2_refs`): {len(changed)}**" + ((" — " + ", ".join(f"`{k}` ({ro[k]['outcome']} → {rn[k]['outcome']})" for k in changed)) if changed else "")
       + f". Full dump not exact on one of the two inputs: {len(inexact)}"
       + ((" — " + ", ".join(f"`{k}` (largest relative error {rn[k]['err']:.1e})" for k in inexact)) if inexact else "") + ".",
       "", f"Best speed-up of 6 and 12 threads, v7 / v6 ({len(ratio)} references with a speed-up on both): median "
       f"{ratio[len(ratio) // 2][0]:.2f}, from {ratio[0][0]:.2f} (`{ratio[0][1]}`) to {ratio[-1][0]:.2f} (`{ratio[-1][1]}`).", "",
       "| reference | size v6 | size v7 | outcome v6 | outcome v7 | best speed-up v6 | v7 | v7 / v6 |", "|---|---|---|---|---|---|---|---|"]
for k in sorted(rn):
    o, n = ro[k], rn[k]
    md.append(f"| `{k}` | {o['size']} | {n['size']} | {o['outcome']} | {n['outcome']} | "
              f"{(format(o['best'], '.2f') + '×') if o['best'] else '—'} | {(format(n['best'], '.2f') + '×') if n['best'] else '—'} | "
              f"{format(n['best'] / o['best'], '.2f') if o['best'] and n['best'] else '—'} |")
(HERE / "t018_readout.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
