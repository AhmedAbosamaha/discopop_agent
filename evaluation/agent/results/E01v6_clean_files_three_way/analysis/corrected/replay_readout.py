#!/usr/bin/env python3
"""E1-v6 corrected — the replay of the rewrites six trials discarded (`checks/e1v6c_replay`, `tools/candidate_replay.py`)
with the harness's verdict on every finished file the pipeline kept (`checks/e1v6c_replay_verify`). No model.

    venv/bin/python evaluation/agent/results/E01v6_clean_files_three_way/analysis/corrected/replay_readout.py
"""
import collections
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
AGENT = HERE.parents[3]
sys.path.insert(0, str(AGENT / "tools"))
sys.path.insert(0, str(AGENT.parent / "shared"))
import campaign  # noqa: E402

root = campaign.find_run("e1v6c_replay")
recs, digests = [], set()
for f in sorted(root.glob("*/results.jsonl")):
    digests.add(str(json.loads((f.parent / "manifest.json").read_text()).get("discopop_pass_sha256"))[:12])
    recs += [json.loads(ln) for ln in f.read_text().splitlines() if ln.strip()]
verdict = {json.loads(ln)["label"]: json.loads(ln) for ln in (root / "verdicts.jsonl").read_text().splitlines() if ln.strip()}
by = {r["label"]: r for r in recs}
trials = collections.defaultdict(list)
for r in recs:
    trials[(r["benchmark"].split("/")[1], r["repeat"])].append(r)
md = ["# E1-v6 corrected — the rewrites six trials discarded, replayed on the fixed DiscoPoP", "",
      f"Generated by `analysis/corrected/replay_readout.py`. No model. Profiler pass `{', '.join(sorted(digests))}`. "
      "Every pragma-free rewrite a trial received and accepted at the first stages, handed to the pipeline with no "
      "attempt left; where the pipeline kept a directive, the finished file judged by the harness against the "
      "benchmark's original (verification size, 6 and 12 threads).", "",
      "| trial | its outcome | candidate | the pipeline today | directives kept | harness: outcome | speed-up at 6 / 12 threads |",
      "|---|---|---|---|---|---|---|"]
could, controls = [], []
for (loop, rep), rows in sorted(trials.items()):
    first = None
    for r in sorted(rows, key=lambda x: x["candidate"]):
        src = by[r["same_as"]] if r.get("same_as") else r
        v = verdict.get(src["label"])
        sp = (v or {}).get("speedups") or {}
        shipped = bool(r.get("is_shipped_rewrite"))
        what = {"KEPT": "kept", "NO_PATTERN": "no pattern", "ALL_REJECTED": f"every directive refused ({', '.join(src.get('rejected_by') or {})})",
                "AGENT_ABORTED": "stops: the rewrite crashes at the timing size" if "non-zero exit (-11)" in str(src.get("detail")) else f"stops: {src.get('detail')}",
                "PATCH_DOES_NOT_APPLY": "patch does not apply"}.get(src["result"], src["result"])
        md.append(f"| `{loop}` repeat {rep} | {r['harness_outcome']} | {r['candidate']}{' — the shipped rewrite' if shipped else ''}"
                  f"{' (same program as candidate ' + str(src['candidate']) + ')' if r.get('same_as') else ''} | {what} | "
                  f"{src.get('applied') if src['result'] == 'KEPT' else '—'} | {(v or {}).get('outcome') or '—'} | "
                  + (f"{sp.get('6'):.2f}× / {sp.get('12'):.2f}×" if sp else "—") + " |")
        if shipped:
            controls.append((loop, rep, r["harness_outcome"], (v or {}).get("outcome")))
        elif (v or {}).get("outcome") == "FASTER" and first is None:
            first = (r["candidate"], max(sp.values()))
    if first and rows[0]["harness_outcome"] != "FASTER":
        could.append((loop, rep, *first))
n_disc = sum(1 for r in recs if not r.get("is_shipped_rewrite"))
md += ["", f"**Rewrites replayed: {len(recs)}** ({len(recs) - n_disc} shipped by their trial, {n_disc} discarded; "
       f"{sum(1 for r in recs if r['result'] == 'KEPT')} finished files kept by the pipeline and verified).", "",
       "**The controls** — the rewrites the trials shipped must give what the trials gave: "
       + "; ".join(f"`{l}` repeat {r}: trial {a}, replay {b}" for l, r, a, b in controls) + ".", "",
       f"**Trials that hold a discarded rewrite the pipeline keeps and the harness judges FASTER: {len(could)}** — "
       + ("; ".join(f"`{l}` repeat {r} (candidate {c}, {s:.2f}×)" for l, r, c, s in could) or "none") + ".",
       "", f"Read as fixed before the run: the corrected count of E1-v6 is 76, and at most {76 + len(could)} had these "
       "trials met the fixed profiler — a replay cannot say what the model would have written next."]
(HERE / "replay_readout.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
