#!/usr/bin/env python3
"""Calibration benchmarks — small programs written for tuning, never for results.

Decision D3 (THESIS_EXPERIMENTS.md §5d) makes the agent's per-region model budget depend on
a region's share of runtime, and the values have to come from measurement: on which attempt
does a region actually succeed? Measuring that on the evaluation benchmarks would tune the
agent on the data it is later judged on. All 37 packaged benchmarks appear in E1, so the
calibration needs programs of its own — these.

They are deliberately small and deliberately varied in difficulty, because the quantity being
measured is the *distribution of attempts until success*, which is meaningless if every
region is trivial (always attempt 1) or impossible (never):

* ``vecsum``    a plain data-parallel loop — should succeed on the first attempt.
* ``dotprod``   a sum reduction — needs a ``reduction`` clause, not just ``parallel for``.
* ``privtemp``  a loop-carried FALSE dependence through one reused scalar — needs
                privatisation; the dependence DiscoPoP reports is real but not a barrier.
* ``prefix``    a genuine prefix-sum recurrence — the correct answer is to decline, or to
                rewrite it as a two-pass scan. It is here so the distribution has a tail.

Each file carries the same packaging as the evaluation benchmarks — digest on stdout,
``-DPB_FULL_DUMP`` for the exact dump, the timed region on stderr, ``argv[1]`` as a
perturbation seed, dataset sizes through ``-D<SIZE>_DATASET`` — so the harness verifies,
scores and scaffolding-checks them exactly as it does the rest. They live under
``agent/prepared/calib/`` and are excluded from every experiment by name.

Usage: ``python3 agent/tools/prepare_calib.py [--validate]``
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Tuple

AGENT_DIR = Path(__file__).resolve().parent.parent
OUT = AGENT_DIR / "prepared" / "calib"
GENERATOR_VERSION = 4   # v4: output_sha256 in meta.json for the runner's integrity check

# Sizes are the same names the harness uses everywhere else, so T0.1 can size these too.
SIZES = """
#if !defined(MINI_DATASET) && !defined(SMALL_DATASET) && !defined(STANDARD_DATASET) \\
    && !defined(LARGE_DATASET) && !defined(EXTRALARGE_DATASET)
# define SMALL_DATASET
#endif
#ifdef MINI_DATASET
# define N %(mini)s
#endif
#ifdef SMALL_DATASET
# define N %(small)s
#endif
#ifdef STANDARD_DATASET
# define N %(standard)s
#endif
#ifdef LARGE_DATASET
# define N %(large)s
#endif
#ifdef EXTRALARGE_DATASET
# define N %(extralarge)s
#endif
"""

SCAFFOLD = """
/* ---- output: digest by default, full dump with -DPB_FULL_DUMP ------------ */
#ifdef PB_FULL_DUMP
# define pb_emit(v) fprintf(stdout, "%0.17g\\n", (double)(v))
# define pb_report() ((void)0)
#else
static unsigned long long pb_count = 0;
static double pb_sum = 0.0;
static double pb_wsum = 0.0;
static void pb_emit(double v)
{
  pb_count++;
  pb_sum += v;
  pb_wsum += v * (double)((pb_count % 9973) + 1);
}
static void pb_report(void)
{
  printf("pb_values %llu\\n", pb_count);
  printf("pb_sum %.17g\\n", pb_sum);
  printf("pb_wsum %.17g\\n", pb_wsum);
}
#endif

/* ---- optional perturbed input: argv[1] = seed ---------------------------- */
static unsigned long long pb_seed(const char* s)
{
  return strtoull(s, NULL, 10) * 0x9E3779B97F4A7C15ULL + 1ULL;
}
static double pb_uniform(unsigned long long* state)
{
  *state = *state * 6364136223846793005ULL + 1442695040888963407ULL;
  return (double)(*state >> 11) / 9007199254740992.0;
}
#define PB_PERTURB(arr, count)                                              \\
  do {                                                                      \\
    double* pb_p = (double*)(arr);                                          \\
    unsigned long long pb_k, pb_n = (unsigned long long)(count);            \\
    for (pb_k = 0; pb_k < pb_n; pb_k++)                                     \\
      pb_p[pb_k] += (double)(pb_uniform(&pb_state) * 3.0);                  \\
  } while (0)

/* ---- timed region: the kernel only --------------------------------------- */
static struct timespec pb_t0;
static void pb_timer_start(void)
{
  clock_gettime(CLOCK_MONOTONIC, &pb_t0);
}
static void pb_timer_stop(void)
{
  struct timespec t1;
  clock_gettime(CLOCK_MONOTONIC, &t1);
  fprintf(stderr, "DP_TIMED_REGION_SECONDS %.9f\\n",
          (double)(t1.tv_sec - pb_t0.tv_sec) + 1e-9 * (double)(t1.tv_nsec - pb_t0.tv_nsec));
}
"""

HEADER = """/* Generated by agent/tools/prepare_calib.py (v%(version)d) — do not edit by hand.
 * CALIBRATION benchmark: used only to tune the agent's per-region budget (decision D3),
 * never in an experiment and never in a reported result.
 *
 * %(what)s
 *
 * Default dataset SMALL; override with -D<SIZE>_DATASET.
 * Prints a value digest to stdout; -DPB_FULL_DUMP prints every value. */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <time.h>
"""


# Every kernel is repeated R times, and every repetition READS what the previous one
# wrote (`c[i] = 0.5 * c[i] + …`). Idempotent repetitions were a hole: a model given no
# evidence "parallelised" the repeat loop by doing all the work in the last repetition
# only — race-free, output-preserving, and no parallel work at all (e2e run, 18 Sep).
class Case:
    def __init__(self, name: str, what: str, sizes: Dict[str, str], arrays: List[Tuple[str, str]],
                 init: str, kernel: str, call: str, dump: str, repeats: str = "R") -> None:
        self.name, self.what, self.sizes = name, what, sizes
        self.arrays, self.init, self.kernel, self.call, self.dump = arrays, init, kernel, call, dump
        self.repeats = repeats


CASES = [
    Case(
        "vecsum", "A plain data-parallel loop: each element is written from its own inputs. "
                  "Nothing blocks parallelisation; DiscoPoP should report a Do-All.",
        # 3 arrays: 70M doubles each keeps the static data under 2 GB (x86-64 Linux
        # cannot link a larger .bss without -mcmodel=medium; that is what killed t0_1_calib).
        {"mini": "1000", "small": "2000000", "standard": "20000000",
         "large": "50000000", "extralarge": "70000000"},
        [("a", "N"), ("b", "N"), ("c", "N")],
        "  for (i = 0; i < N; i++) { a[i] = (double)(i % 977) * 0.5; b[i] = (double)(i % 331) * 0.25; }",
        "static void kernel_vecsum(double* a, double* b, double* c)\n"
        "{\n  int r, i;\n  for (r = 0; r < R; r++)\n"
        "    for (i = 0; i < N; i++)\n      c[i] = 0.5 * c[i] + a[i] * b[i] + 0.5 * a[i];\n}",
        "kernel_vecsum(a, b, c);",
        "  for (i = 0; i < N; i += (N / 512 > 0 ? N / 512 : 1)) pb_emit(c[i]);",
    ),
    Case(
        "dotprod", "A sum reduction. `parallel for` alone is a race: the accumulator needs a "
                   "reduction clause, so this separates 'found the loop' from 'got the clause right'.",
        # 2 arrays: 100M doubles each = 1.6 GB of static data (see vecsum).
        {"mini": "1000", "small": "2000000", "standard": "20000000",
         "large": "60000000", "extralarge": "100000000"},
        [("a", "N"), ("b", "N")],
        "  for (i = 0; i < N; i++) { a[i] = (double)(i % 613) * 0.125; b[i] = (double)(i % 149) * 0.75; }",
        "static double kernel_dotprod(double* a, double* b)\n"
        "{\n  int r, i;\n  double acc = 0.0;\n  for (r = 0; r < R; r++)\n"
        "    for (i = 0; i < N; i++)\n      acc += a[i] * b[i];\n  return acc;\n}",
        "result = kernel_dotprod(a, b);",
        "  pb_emit(result);",
    ),
    Case(
        "privtemp", "One reused scalar carries a FALSE dependence across iterations. The "
                    "dependence DiscoPoP reports is real; privatising the scalar removes it. "
                    "A rewrite that hoists the computation instead is also correct.",
        {"mini": "1000", "small": "1000000", "standard": "10000000",
         "large": "30000000", "extralarge": "60000000"},
        [("a", "N"), ("c", "N")],
        "  for (i = 0; i < N; i++) a[i] = (double)(i % 457) * 0.3;",
        "static void kernel_privtemp(double* a, double* c)\n"
        "{\n  int r, i;\n  double t;\n  for (r = 0; r < R; r++)\n    for (i = 0; i < N; i++) {\n"
        "      t = a[i] * a[i] + 1.0;\n      c[i] = 0.5 * c[i] + t * 0.5 + sqrt(t);\n    }\n}",
        "kernel_privtemp(a, c);",
        "  for (i = 0; i < N; i += (N / 512 > 0 ? N / 512 : 1)) pb_emit(c[i]);",
    ),
    Case(
        "prefix", "A genuine prefix-sum recurrence: element i needs element i-1. The correct "
                  "answers are to decline, or to rewrite it as a two-pass scan. It gives the "
                  "attempt distribution a tail — without it every region would be easy.",
        {"mini": "1000", "small": "1000000", "standard": "10000000",
         "large": "30000000", "extralarge": "60000000"},
        [("a", "N"), ("c", "N")],
        "  for (i = 0; i < N; i++) a[i] = (double)(i % 251) * 0.02;",
        "static void kernel_prefix(double* a, double* c)\n"
        "{\n  int r, i;\n  for (r = 0; r < R; r++) {\n    c[0] = 0.5 * c[0] + a[0];\n"
        "    for (i = 1; i < N; i++)\n      c[i] = c[i-1] + a[i];\n  }\n}",
        "kernel_prefix(a, c);",
        "  for (i = 0; i < N; i += (N / 512 > 0 ? N / 512 : 1)) pb_emit(c[i]);",
    ),
]


def render(case: Case) -> str:
    decls = "".join(f"static double {n}[{s}];\n" for n, s in case.arrays)
    perturb = "\n".join(f"      PB_PERTURB({n}, {s});" for n, s in case.arrays
                        if n in ("a", "b"))
    needs_result = "result" in case.call
    return (
        HEADER % {"version": GENERATOR_VERSION, "what": case.what}
        + SIZES % case.sizes
        + "\n#define R 4\n"   # repetitions read what the previous one wrote (see Case docs)
        + SCAFFOLD
        + "\n/* ---- the program under study -------------------------------------------- */\n"
        + decls
        + "\nstatic void init_array(void)\n{\n  int i;\n" + case.init + "\n}\n\n"
        + case.kernel + "\n\n"
        + "int main(int argc, char** argv)\n{\n  int i;\n"
        + ("  double result = 0.0;\n" if needs_result else "")
        + "  init_array();\n\n"
        + "  /* Optional perturbed input, see PB_PERTURB. */\n"
        + "  if (argc > 1)\n    {\n      unsigned long long pb_state = pb_seed(argv[1]);\n"
        + perturb + "\n    }\n\n"
        + "  pb_timer_start();\n  " + case.call + "\n  pb_timer_stop();\n\n"
        + case.dump + "\n\n  pb_report();\n  return 0;\n}\n"
    )


def render_project(case: Case) -> Dict[str, str]:
    """The same program as `render`, as a PROJECT: the kernel in a unit of its own.

    Three files — `include/bench.h` (sizes, arrays, the kernel's prototype),
    `src/kernel.c` (the arrays and the kernel) and `src/main.c` (packaging, input, main) —
    so the code under study lives OUTSIDE the unit that holds `main`. That is the case
    DiscoPoP gets wrong when a program is profiled unit by unit (THESIS_EXPERIMENTS.md
    §5g D6), and the case the harness's project path has to get right."""
    includes = HEADER.split("#include", 1)
    system = "#include" + includes[1]
    sig = case.kernel.split("\n", 1)[0].replace("static ", "", 1)
    header = (
        "/* Generated by agent/tools/prepare_calib.py (v%d) — calibration, project layout. */\n"
        "#ifndef BENCH_H\n#define BENCH_H\n" % GENERATOR_VERSION
        + system + SIZES % case.sizes + "\n#define R 4\n\n"
        + "".join(f"extern double {n}[{s}];\n" for n, s in case.arrays)
        + sig + ";\n#endif\n")
    kernel = ('#include "bench.h"\n\n'
              + "".join(f"double {n}[{s}];\n" for n, s in case.arrays) + "\n"
              + case.kernel.replace("static ", "", 1) + "\n")
    perturb = "\n".join(f"      PB_PERTURB({n}, {s});" for n, s in case.arrays if n in ("a", "b"))
    needs_result = "result" in case.call
    main_c = (
        (includes[0] % {"version": GENERATOR_VERSION, "what": case.what})
        + '#include "bench.h"\n' + SCAFFOLD
        + "\n/* ---- input and driver; the kernel is in src/kernel.c ------------------- */\n"
        + "static void init_array(void)\n{\n  int i;\n" + case.init + "\n}\n\n"
        + "int main(int argc, char** argv)\n{\n  int i;\n"
        + ("  double result = 0.0;\n" if needs_result else "")
        + "  init_array();\n\n"
        + "  /* Optional perturbed input, see PB_PERTURB. */\n"
        + "  if (argc > 1)\n    {\n      unsigned long long pb_state = pb_seed(argv[1]);\n"
        + perturb + "\n    }\n\n"
        + "  pb_timer_start();\n  " + case.call + "\n  pb_timer_stop();\n\n"
        + case.dump + "\n\n  pb_report();\n  return 0;\n}\n")
    return {"include/bench.h": header, "src/kernel.c": kernel, "src/main.c": main_c}


PROJECT_UNITS = ["src/kernel.c", "src/main.c"]


def _cc() -> str:
    """The C compiler to validate with: $DP_CC, else the first that exists.

    The server has `clang-20` and no plain `clang`, and the same names are used by
    `size_table.py` and the harness, so a generated benchmark is checked with the compiler
    it will actually be built with."""
    for c in [os.environ.get("DP_CC", ""), "clang-20", "clang-19", "clang", "cc"]:
        if c and shutil.which(c):
            return c
    return "cc"


def _sysroot() -> List[str]:
    """On macOS, Homebrew's clang needs the SDK path (`-isysroot`), as the harness adds it."""
    if sys.platform != "darwin":
        return []
    try:
        sdk = subprocess.check_output(["xcrun", "--show-sdk-path"], text=True,
                                      stderr=subprocess.DEVNULL).strip()
    except (OSError, subprocess.CalledProcessError):
        return []
    return ["-isysroot", sdk] if sdk else []


def validate(path: Path, name: str) -> List[str]:
    """Every property the harness relies on, checked on the generated file — or, when
    `path` is a directory, on the generated project."""
    problems: List[str] = []
    inputs = ([str(path / u) for u in PROJECT_UNITS] + [f"-I{path / 'include'}"]
              if path.is_dir() else [str(path)])
    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp)
        for label, flags in (("digest", []), ("dump", ["-DPB_FULL_DUMP"])):
            r = subprocess.run([_cc(), "-O2", *_sysroot(), "-DMINI_DATASET", *flags, *inputs,
                                "-o", str(d / label), "-lm"], capture_output=True, text=True)
            if r.returncode != 0:
                problems.append(f"{label} build failed: {r.stderr.strip().splitlines()[:1]}")
                return problems
        run = subprocess.run([str(d / "digest")], capture_output=True, text=True, timeout=120)
        lines = run.stdout.split()
        if run.returncode != 0:
            problems.append(f"run failed: rc={run.returncode}")
        if "DP_TIMED_REGION_SECONDS" not in run.stderr:
            problems.append("no timed region on stderr")
        if len(lines) != 6 or lines[0] != "pb_values":
            problems.append(f"digest is not 3 lines: {run.stdout[:60]!r}")
        seeded = subprocess.run([str(d / "digest"), "7"], capture_output=True, text=True, timeout=120)
        if seeded.stdout == run.stdout:
            problems.append("the perturbed input does not change the output")
        dump = subprocess.run([str(d / "dump")], capture_output=True, text=True, timeout=120)
        vals = dump.stdout.split()
        if not vals:
            problems.append("the full dump is empty")
        if any(v != v.strip() or not _isfloat(v) for v in vals[:5]):
            problems.append(f"the dump is not numeric: {vals[:3]}")
        again = subprocess.run([str(d / "digest")], capture_output=True, text=True, timeout=120)
        if again.stdout != run.stdout:
            problems.append("two runs disagree — the program is not deterministic")
    return problems


def _isfloat(x: str) -> bool:
    try:
        float(x)
        return True
    except ValueError:
        return False


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--validate", action="store_true", help="build and check each generated program")
    ap.add_argument("--layout", choices=["single", "project", "both"], default="single",
                    help=("single (default): one file per benchmark, as the evaluation is packaged. "
                          "project: the same programs as multi-file projects under <name>_proj/, "
                          "kernel in a unit of its own — for testing the project path."))
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    failed = 0
    for case in (CASES if a.layout in ("project", "both") else []):
        d = OUT / f"{case.name}_proj"
        shutil.rmtree(d, ignore_errors=True)
        files = render_project(case)
        for rel, text in files.items():
            (d / rel).parent.mkdir(parents=True, exist_ok=True)
            (d / rel).write_text(text)
        (d / "meta.json").write_text(json.dumps({
            "suite": "calibration", "kernel": f"{case.name}_proj",
            "source": "agent/tools/prepare_calib.py", "category": "calibration",
            "file": "src/main.c", "language": "c", "layout": "project",
            "project": {"units": PROJECT_UNITS, "include_dirs": ["include"]},
            "exclude_functions": ["init_array", "pb_emit", "pb_report", "pb_seed",
                                  "pb_uniform", "pb_timer_start", "pb_timer_stop", "main"],
            "agent_dataset": "SMALL", "generator_version": GENERATOR_VERSION,
            "note": "calibration only, project layout — never in an experiment or a reported result",
            # the runner's integrity check compares the package against this digest
            "output_sha256": hashlib.sha256(
                "".join(files[k] for k in sorted(files)).encode()).hexdigest(),
        }, indent=2) + "\n")
        note = ""
        if a.validate:
            problems = validate(d, case.name)
            failed += bool(problems)
            note = "  OK" if not problems else "  FAILED: " + "; ".join(problems)
        print(f"{case.name + '_proj':14s} 3 files{note}")
    for case in (CASES if a.layout in ("single", "both") else []):
        d = OUT / case.name
        d.mkdir(parents=True, exist_ok=True)
        src = d / f"{case.name}.c"
        src.write_text(render(case))
        (d / "meta.json").write_text(json.dumps({
            "suite": "calibration", "kernel": case.name,
            "source": "agent/tools/prepare_calib.py", "category": "calibration",
            "file": src.name, "language": "c",
            "exclude_functions": ["init_array", "pb_emit", "pb_report", "pb_seed",
                                  "pb_uniform", "pb_timer_start", "pb_timer_stop", "main"],
            "agent_dataset": "SMALL", "generator_version": GENERATOR_VERSION,
            "note": "calibration only (decision D3) — never in an experiment or a reported result",
            "output_sha256": hashlib.sha256(src.read_bytes()).hexdigest(),
        }, indent=2) + "\n")
        note = ""
        if a.validate:
            problems = validate(src, case.name)
            failed += bool(problems)
            note = "  OK" if not problems else "  FAILED: " + "; ".join(problems)
        print(f"{case.name:10s} {len(src.read_text().splitlines()):4d} lines{note}")
    print(f"wrote {len(CASES)} calibration benchmarks to {OUT}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
